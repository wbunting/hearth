//! IR → Toasty lowering for server-side first-view queries.
//!
//! `#[derive(Table)]` generates a `SqlColumns` impl that knows, per column,
//! how to build a typed Toasty filter (`eq/ne/lt/.../in/contains`) and
//! order-by from JSON values. [`base_query`] walks the base-table part of a
//! query's IR and pushes everything it can into SQL:
//!
//! - `where`: conjunctions/disjunctions/negations of column-vs-param/literal
//!   comparisons on the base alias; `if $(cond) { … }` is resolved with the
//!   param value (dropped when falsy). Anything else (e.g. a predicate on a
//!   joined alias) is left for the in-memory pass.
//! - `order by` on base columns, `limit` (only when the whole `where` was
//!   pushed down; otherwise over-fetch).
//!
//! Joins are then satisfied with one `in_list` query per joined table on
//! the join keys collected from the base rows.

use serde_json::Value;

use crate::ir::{Expr, Query};

/// Per-table column lowering (generated by `#[derive(Table)]`).
pub trait SqlColumns {
    type Model: toasty::schema::Model;
    /// `col <op> value` as a Toasty filter, or `None` if unsupported.
    fn cmp(col: &str, op: &str, value: &Value) -> Option<toasty::stmt::Expr<bool>>;
    /// Order-by for a column.
    fn order(col: &str, desc: bool) -> Option<toasty::stmt::OrderByExpr>;
}

/// Result of lowering: the pushed-down filter, and whether it covers the
/// whole `where` (if not, the caller must not apply `limit` in SQL).
pub struct Lowered {
    pub filter: Option<toasty::stmt::Expr<bool>>,
    pub complete: bool,
}

pub fn lower_where<C: SqlColumns>(q: &Query, params: &[Value]) -> Lowered {
    match &q.where_ {
        None => Lowered { filter: None, complete: true },
        Some(w) => match lower::<C>(w, q.from.alias, params) {
            Some(Some(f)) => Lowered { filter: Some(f), complete: true },
            Some(None) => Lowered { filter: None, complete: true }, // always-true
            None => Lowered { filter: partial::<C>(w, q.from.alias, params), complete: false },
        },
    }
}

/// `Some(Some(f))` = filter f; `Some(None)` = always true; `None` = not lowerable.
fn lower<C: SqlColumns>(e: &Expr, alias: &str, params: &[Value]) -> Option<Option<toasty::stmt::Expr<bool>>> {
    match e {
        Expr::Bin { op, l, r } => {
            let (col, val, op) = match (&**l, &**r) {
                (Expr::Col { col: (a, c) }, v) if *a == alias => (*c, value(v, params)?, *op),
                (v, Expr::Col { col: (a, c) }) if *a == alias => (*c, value(v, params)?, flip(op)),
                _ => return None,
            };
            C::cmp(col, op, &val).map(Some)
        }
        Expr::Col { col: (a, c) } if *a == alias => C::cmp(c, "eq", &Value::Bool(true)).map(Some),
        Expr::Many { op, args } => {
            let mut parts = Vec::new();
            for a in args {
                match lower::<C>(a, alias, params)? {
                    Some(f) => parts.push(f),
                    None if *op == "or" => return Some(None), // `true || x`
                    None => {}
                }
            }
            let mut it = parts.into_iter();
            let Some(first) = it.next() else { return Some(None) };
            Some(Some(it.fold(first, |acc, f| if *op == "and" { acc.and(f) } else { acc.or(f) })))
        }
        Expr::Not { arg, .. } => match lower::<C>(arg, alias, params)? {
            Some(f) => Some(Some(f.not())),
            None => None, // `!true` = false: let the in-memory pass handle it
        },
        Expr::If { cond, then, .. } => {
            if crate::ir::truthy(&value(cond, params)?) { lower::<C>(then, alias, params) } else { Some(None) }
        }
        _ => None,
    }
}

/// Best-effort: the lowerable conjuncts of a top-level `and`.
fn partial<C: SqlColumns>(e: &Expr, alias: &str, params: &[Value]) -> Option<toasty::stmt::Expr<bool>> {
    let Expr::Many { op: "and", args } = e else { return None };
    let parts: Vec<_> = args.iter().filter_map(|a| lower::<C>(a, alias, params).flatten()).collect();
    let mut it = parts.into_iter();
    let first = it.next()?;
    Some(it.fold(first, toasty::stmt::Expr::and))
}

fn value(e: &Expr, params: &[Value]) -> Option<Value> {
    match e {
        Expr::Lit { lit } => Some(lit.clone()),
        Expr::Param { param } => params.get(*param).cloned(),
        _ => None,
    }
}

fn flip(op: &'static str) -> &'static str {
    match op {
        "lt" => "gt",
        "gt" => "lt",
        "lte" => "gte",
        "gte" => "lte",
        o => o,
    }
}

/// Order-by for the base table. A total order: ties are broken by the
/// primary key (ascending), exactly like the browser engine and the SSR
/// evaluator, so the first page is identical everywhere (otherwise equal
/// sort keys come back in arbitrary SQL order and the list reshuffles on
/// hydration).
pub fn order<C: SqlColumns>(q: &Query, params: &[Value], key: &str) -> Vec<toasty::stmt::OrderByExpr> {
    let _ = params;
    let mut out: Vec<_> = q
        .order
        .iter()
        .map_while(|o| match &o.expr {
            Expr::Col { col: (a, c) } if *a == q.from.alias => C::order(c, o.desc),
            _ => None,
        })
        .collect();
    let complete = out.len() == q.order.len();
    let by_key = q.order.iter().any(|o| matches!(&o.expr, Expr::Col { col: (a, c) } if *a == q.from.alias && *c == key));
    if complete && !by_key && !out.is_empty() {
        out.extend(C::order(key, false));
    }
    out
}

/// `%text%` with LIKE metacharacters escaped by `\`.
#[must_use]
pub fn contains_pattern(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('%');
    for c in text.chars() {
        if matches!(c, '%' | '_' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('%');
    out
}
